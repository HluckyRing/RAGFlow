# 拒答标记：模型答不出时必须以它开头，后端据此推 refused 事件、前端据此单独渲染。
# 用「结构化前缀」而不是事后猜文案（2026-11-06）：只靠「有没有『没有提到』」这种启发式
# 判定，正常回答里引用到「没有提到」就会被误标成拒答。
REFUSAL_MARKER = "【无答案】"

# 拆问（query 分解）的系统提示词。为什么要 JSON 数组（2026-11-08 实测四版提示词）：
# 「每行一个」在子问题本身带换行或带编号时会脏，「1. 2. 3.」要额外剥编号，而 JSON 数组
# 一次就能确定「几条、分别是什么」；四版在 8 条样例上行为一致（单问都不拆、逗号/连写
# 都能拆开），所以选解析最稳的那一版。**要求原样返回单问**是因为拆出来的同义改写会让
# 检索变差且没有任何收益 —— 代码里还有一条保险丝：只拆出一条时直接用原问句。
DECOMPOSE_SYSTEM_PROMPT = (
    "你是检索助手。把用户的问题拆成若干**独立的子问题**，用于分别检索同一个知识库。\n"
    "规则：\n"
    "1. 只在问题里确实问了多件事时才拆；只有一件事就**原样**返回一条，不要改写成同义句。\n"
    "2. 每个子问题必须能单独看懂，并保留原问里的关键名词与限定语（不要丢掉「一线城市」"
    "「C 级客户」这类条件）。\n"
    "3. 按原问的先后顺序排列；不要合并，也不要补问原问没问的东西。\n"
    "4. 不要回答问题、不要解释、不要编号。\n"
    '5. 只输出一个 JSON 数组，例如：["子问题一", "子问题二"]'
)

